-- بيانات العميل: البطاقة اختيارية ومكررة مسموحة، والعنوان اختياري.
alter table public.clients add column if not exists address text not null default '';
alter table public.clients alter column national_id set default '';
alter table public.clients drop constraint if exists clients_national_id_key;
alter table public.clients drop constraint if exists clients_national_id_check;
update public.clients set national_id = '' where national_id is null;
alter table public.clients add constraint clients_national_id_check
  check (national_id = '' or national_id ~ '^[0-9]{14}$') not valid;

-- حقول الحركة المالية.
alter table public.payments add column if not exists statement text not null default '';
alter table public.payments add column if not exists payer_name text not null default '';
alter table public.payments drop constraint if exists payments_payer_name_required;
alter table public.payments add constraint payments_payer_name_required
  check (length(trim(payer_name)) > 0) not valid;

-- سجل التعديلات: التاريخ والوقت، المستخدم، نوع العملية والحقول التي تغيرت.
create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  table_name text not null,
  record_id text not null,
  action text not null,
  actor_id uuid,
  actor_email text not null default 'غير معروف',
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists audit_logs_created_at_idx on public.audit_logs(created_at desc);
alter table public.audit_logs enable row level security;
drop policy if exists "authenticated users can read audit logs" on public.audit_logs;
create policy "authenticated users can read audit logs" on public.audit_logs
  for select to authenticated using (true);
grant select on public.audit_logs to authenticated;
grant usage, select on sequence public.audit_logs_id_seq to authenticated;

create or replace function public.capture_alwaleed_audit_log()
returns trigger
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_actor uuid;
  v_email text := 'غير معروف';
  v_old jsonb := '{}'::jsonb;
  v_new jsonb := '{}'::jsonb;
  v_details jsonb := '{}'::jsonb;
  v_key text;
  v_record_id text;
begin
  v_actor := auth.uid();
  if v_actor is not null then
    select email into v_email from auth.users where id = v_actor;
    v_email := coalesce(v_email, 'مستخدم مسجل');
  end if;

  if TG_OP = 'INSERT' then
    v_new := to_jsonb(NEW);
    v_record_id := coalesce(v_new->>'id', '');
    for v_key in select jsonb_object_keys(v_new) loop
      if v_key not in ('created_at','updated_at','national_id') then
        v_details := v_details || jsonb_build_object(v_key,
          jsonb_build_object('old', null, 'new', v_new->v_key));
      elsif v_key = 'national_id' then
        v_details := v_details || jsonb_build_object(v_key,
          jsonb_build_object('old', null, 'new', '[مخفي]'));
      end if;
    end loop;
  elsif TG_OP = 'UPDATE' then
    v_old := to_jsonb(OLD); v_new := to_jsonb(NEW);
    v_record_id := coalesce(v_new->>'id', '');
    for v_key in select jsonb_object_keys(v_new) loop
      if v_key not in ('created_at','updated_at') and (v_old->v_key) is distinct from (v_new->v_key) then
        if v_key = 'national_id' then
          v_details := v_details || jsonb_build_object(v_key,
            jsonb_build_object('old', '[مخفي]', 'new', '[مخفي]'));
        else
          v_details := v_details || jsonb_build_object(v_key,
            jsonb_build_object('old', v_old->v_key, 'new', v_new->v_key));
        end if;
      end if;
    end loop;
  else
    v_old := to_jsonb(OLD);
    v_record_id := coalesce(v_old->>'id', '');
    for v_key in select jsonb_object_keys(v_old) loop
      if v_key not in ('created_at','updated_at','national_id') then
        v_details := v_details || jsonb_build_object(v_key,
          jsonb_build_object('old', v_old->v_key, 'new', null));
      elsif v_key = 'national_id' then
        v_details := v_details || jsonb_build_object(v_key,
          jsonb_build_object('old', '[مخفي]', 'new', null));
      end if;
    end loop;
  end if;

  insert into public.audit_logs(table_name, record_id, action, actor_id, actor_email, details)
  values (TG_TABLE_NAME, v_record_id, TG_OP, v_actor, v_email, v_details);

  if TG_OP = 'DELETE' then return OLD; else return NEW; end if;
end;
$$;

drop trigger if exists clients_audit_log on public.clients;
create trigger clients_audit_log after insert or update or delete on public.clients
  for each row execute function public.capture_alwaleed_audit_log();
drop trigger if exists payments_audit_log on public.payments;
create trigger payments_audit_log after insert or update or delete on public.payments
  for each row execute function public.capture_alwaleed_audit_log();

