create extension if not exists pgcrypto;
create table if not exists public.clients (
 id bigint generated by default as identity primary key,
 full_name text not null check (char_length(trim(full_name)) between 2 and 160),
 mobile text not null unique check (mobile ~ '^[0-9]{11}$'),
 landline text not null default '',
 national_id text not null default '' check (national_id = '' or national_id ~ '^[0-9]{14}$'),
 address text not null default '',
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.payments (
 id uuid primary key default gen_random_uuid(), client_id bigint not null references public.clients(id) on delete cascade,
 amount_due numeric(12,2) not null default 0 check (amount_due >= 0),
 amount_paid numeric(12,2) not null default 0 check (amount_paid >= 0),
 payment_date date not null default current_date, statement text not null default '', notes text not null default '', created_at timestamptz not null default now()
);
create index if not exists clients_name_idx on public.clients(full_name);
create index if not exists clients_mobile_idx on public.clients(mobile);
create index if not exists payments_client_date_idx on public.payments(client_id,payment_date desc);
alter table public.clients enable row level security;
alter table public.payments enable row level security;
drop policy if exists "authenticated users can manage clients" on public.clients;
create policy "authenticated users can manage clients" on public.clients for all to authenticated using (true) with check (true);
drop policy if exists "authenticated users can manage payments" on public.payments;
create policy "authenticated users can manage payments" on public.payments for all to authenticated using (true) with check (true);
grant usage on schema public to authenticated;
grant select,insert,update,delete on public.clients to authenticated;
grant select,insert,update,delete on public.payments to authenticated;
grant usage,select on all sequences in schema public to authenticated;
